/**
 * Build step. There is no bundler dependency: the sources are plain ES modules
 * with named exports, so stripping the import/export keywords and concatenating
 * them in dependency order is enough.
 *
 * Outputs:
 *   index.html  - self-contained app, works from file:// with no server
 *   worker.js   - standalone parsing worker (JSZip + parser)
 *
 * Both are committed so GitHub Pages needs no build, and the CSP carries the
 * sha256 of the inlined script so script-src stays strict.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(here, p), "utf8");

/** Strip module syntax so files can be concatenated into one classic script. */
function strip(src) {
  return src
    .replace(/^[ \t]*import\s+[^;]*?;[ \t]*$/gm, "")
    .replace(/^[ \t]*export\s+\{[^}]*\}\s*;?[ \t]*$/gm, "")
    .replace(/^([ \t]*)export\s+/gm, "$1")
    .trim();
}

const jszip = read("vendor/jszip.min.js");
// Dependency order matters: concatenation has no module resolver, so each file
// must come after everything it refers to. db <- store <- gather <- ui/worker.
const parts = {
  db: strip(read("src/db.js")),
  parse: strip(read("src/parse.js")),
  store: strip(read("src/store.js")),
  gather: strip(read("src/gather.js")),
  i18n: strip(read("src/i18n.js")),
  crypt: strip(read("src/crypt.js")),
  card: strip(read("src/card.js")),
  ui: strip(read("src/ui.js")),
  worker: strip(read("src/worker.js"))
};

const banner = (what) =>
  `/* FOLLOW/BACK - ${what}. Generated by build.js from src/. Edit src/, then run: npm run build */\n`;

/* ---- worker.js ---- */
const workerOut =
  banner("parsing worker") +
  jszip +
  "\n" +
  ";(function(){\n" +
  parts.db +
  "\n" +
  parts.parse +
  "\n" +
  parts.store +
  "\n" +
  parts.gather +
  "\n" +
  parts.worker +
  "\n})();\n";
writeFileSync(join(here, "worker.js"), workerOut);

/* ---- index.html ---- */
const script =
  banner("app") +
  jszip +
  "\n" +
  ";(function(){\n" +
  parts.db +
  "\n" +
  parts.parse +
  "\n" +
  parts.store +
  "\n" +
  parts.gather +
  "\n" +
  parts.i18n +
  "\n" +
  parts.crypt +
  "\n" +
  parts.card +
  "\n" +
  parts.ui +
  "\n})();\n";

const sha = "sha256-" + createHash("sha256").update(script, "utf8").digest("base64");
const csp = [
  "default-src 'none'",
  `script-src '${sha}'`,
  "worker-src 'self' blob:",
  "style-src 'unsafe-inline'",
  "img-src 'self' data:",
  "manifest-src 'self'",
  "connect-src 'none'",
  "base-uri 'none'",
  "form-action 'none'"
].join("; ");

const html = read("src/index.template.html")
  .replace("<!--CSP-->", `<meta http-equiv="Content-Security-Policy" content="${csp}">`)
  .replace("<!--STYLE-->", () => read("src/style.css").trim())
  .replace("<!--SCRIPT-->", () => script);

writeFileSync(join(here, "index.html"), html);

/* ---- _headers (Netlify) ----
 * The same policy again as a real HTTP header, which also allows
 * frame-ancestors (ignored in a meta tag). Only the page gets it: sw.js has to
 * fetch, and connect-src 'none' on its own response would stop it. */
const pageCsp = `  Content-Security-Policy: ${csp}; frame-ancestors 'none'`;
const headers = [
  "# Generated by build.js. Edit build.js, then run: npm run build",
  "/",
  pageCsp,
  "/index.html",
  pageCsp,
  "/*",
  "  X-Content-Type-Options: nosniff",
  "  Referrer-Policy: no-referrer",
  "  X-Frame-Options: DENY",
  "  Cross-Origin-Opener-Policy: same-origin",
  "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()",
  ""
].join("\n");
writeFileSync(join(here, "_headers"), headers);

const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0) + " KB";
console.log(`index.html ${kb(html)}  worker.js ${kb(workerOut)}`);
console.log(`CSP script hash ${sha}`);
